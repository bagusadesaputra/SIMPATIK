    private void tabel_karyawanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabel_karyawanMouseClicked
        int selectedRow = tabel_karyawan.getSelectedRow();
        if(selectedRow != -1) {
            String kode     = tabel_karyawan.getValueAt(selectedRow, 0).toString();
            String nama     = tabel_karyawan.getValueAt(selectedRow, 1).toString();
            String jk       = tabel_karyawan.getValueAt(selectedRow, 2).toString();
            String telepon  = tabel_karyawan.getValueAt(selectedRow, 3).toString();
            String alamat   = tabel_karyawan.getValueAt(selectedRow, 4).toString();
            
            t_kode.setText(kode);
            t_namaKaryawan.setText(nama);
            combo_jenisKelamin.setSelectedItem(jk);
            t_noHP.setText(telepon);
            t_alamat.setText(alamat);
        
            mainPanel.removeAll();
            mainPanel.repaint();
            mainPanel.revalidate();

            mainPanel.add(tambahKaryawan);
            mainPanel.repaint();
            mainPanel.revalidate();
        }
        
        btn_simpan.setEnabled(false);
        btn_update.setEnabled(true);
        btn_hapus.setEnabled(true);
    }//GEN-LAST:event_tabel_karyawanMouseClicked

    private void t_cariKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_t_cariKeyTyped
        DefaultTableModel model = (DefaultTableModel) tabel_karyawan.getModel();
        model.setRowCount(0);
        
        String cari = t_cari.getText();
        
        try {
            String sql = "SELECT * FROM karyawan WHERE kode_karyawan LIKE ? OR nama LIKE ? OR no_hp LIKE ? OR alamat LIKE ?";
            PreparedStatement st = conn.prepareStatement(sql);
                st.setString(1, "%" + cari + "%");
                st.setString(2, "%" + cari + "%");
                st.setString(3, "%" + cari + "%");
                st.setString(4, "%" + cari + "%");
            
            ResultSet rs = st.executeQuery();
            
            while(rs.next()) {
                Object[] rowData = {
                    rs.getString("kode_karyawan"),
                    rs.getString("nama"),
                    rs.getString("jenis_kelamin"),
                    rs.getString("no_hp"),
                    rs.getString("alamat")
                };
                model.addRow(rowData);
            }
            
            rs.close();
            st.close();
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error fetching karyawan data", e);
        }
    }//GEN-LAST:event_t_cariKeyTyped


