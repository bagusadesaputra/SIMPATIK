    private void btn_hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_hapusActionPerformed
        int selectedRow = tabel_karyawan.getSelectedRow();
        if(selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data yang ingin di hapus!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Apakah anda yakin ingin menghapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            String id = tabel_karyawan.getValueAt(selectedRow, 0).toString();
            
            try {
                String sql = "DELETE FROM karyawan WHERE kode_karyawan=?";
                PreparedStatement st = conn.prepareStatement(sql);
                st.setString(1, id);
                
                int rowDelete = st.executeUpdate();
                if (rowDelete > 0) {
                    JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
                    resetForm();
                    getData();
                    aktifButton();
                    nonAktifButton();
                }
                
                st.close();
            } catch(Exception e) {
                logger.log(Level.SEVERE, "Error fetching karyawan data", e);
            }
        }
    }//GEN-LAST:event_btn_hapusActionPerformed

    private void btn_updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_updateActionPerformed
        int selectedRow = tabel_karyawan.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data yang ingin di perbarui!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String kode = t_kode.getText().trim();
        String nama = t_namaKaryawan.getText().trim();
        String jk = (String) combo_jenisKelamin.getSelectedItem();
        String telepon = t_noHP.getText().trim();
        String alamat = t_alamat.getText().trim();

        if (kode.isEmpty() || nama.isEmpty() || jk == null || jk.startsWith("--") || telepon.isEmpty() || alamat.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua kolom harus diisi!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String sql = "UPDATE karyawan SET nama=?, jenis_kelamin=?, no_hp=?, alamat=? WHERE kode_karyawan=?";
        try (PreparedStatement st = conn.prepareStatement(sql)) {
            st.setString(1, nama);
            st.setString(2, jk);
            st.setString(3, telepon);
            st.setString(4, alamat);
            st.setString(5, kode);

            int rowUpdated = st.executeUpdate();
            if (rowUpdated > 0) {
                JOptionPane.showMessageDialog(this, "Data berhasil di perbarui!");
                resetForm();
                nonAktifButton();
                aktifButton();
                getData();
            } else {
                JOptionPane.showMessageDialog(this, "Data tidak ditemukan atau tidak ada perubahan.", "Info", JOptionPane.WARNING_MESSAGE);
            }
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error updating karyawan data", e);
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan saat memperbarui data.", "Error", JOptionPane.ERROR_MESSAGE);
        }
        
        mainPanel.removeAll();
        mainPanel.repaint();
        mainPanel.revalidate();
        
        mainPanel.add(dataKaryawan);
        mainPanel.repaint();
        mainPanel.revalidate();
    }//GEN-LAST:event_btn_updateActionPerformed

