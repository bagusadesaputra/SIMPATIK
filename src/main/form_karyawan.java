    private void getData() {
        DefaultTableModel model = (DefaultTableModel) tabel_karyawan.getModel();
        model.setRowCount(0);

        if (conn == null) {
            return; // Koneksi.getConnection() sudah menampilkan pesan error
        }

        String sql = "SELECT * FROM karyawan";

        try (PreparedStatement st = conn.prepareStatement(sql); ResultSet rs = st.executeQuery()) {

            while (rs.next()) {
                Object[] rowData = {
                    rs.getString("kode_karyawan"),
                    rs.getString("nama"),
                    rs.getString("jenis_kelamin"),
                    rs.getString("no_hp"),
                    rs.getString("alamat")
                };
                model.addRow(rowData);
            }

        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error fetching karyawan data", e);
        }
    }

