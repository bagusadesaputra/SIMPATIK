    private void btn_simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_simpanActionPerformed
        String kode = t_kode.getText();
        String nama = t_namaKaryawan.getText();
        String jk = (String) combo_jenisKelamin.getSelectedItem();
        String telepon = t_noHP.getText();
        String alamat = t_alamat.getText();
        
        if(kode.isEmpty() || nama.isEmpty() || jk == null || jk.startsWith("--") || telepon.isEmpty() || alamat.isEmpty()){
            JOptionPane.showMessageDialog(this, "Semua kolom harus diisi!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try {
            String sql = "INSERT INTO karyawan (kode_karyawan, nama, jenis_kelamin, no_hp, alamat) VALUES (?,?,?,?,?)";
            PreparedStatement st = conn.prepareStatement(sql);
            st.setString(1, kode);
            st.setString(2, nama);
            st.setString(3, jk);
            st.setString(4, telepon);
            st.setString(5, alamat);
            
            int rowInserted = st.executeUpdate();
            if (rowInserted > 0){
                JOptionPane.showMessageDialog(this, "Data berhasil di input!");
                resetForm();
                getData();
            }
            st.close();
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error inserting karyawan data", e);
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data. Periksa apakah kode karyawan sudah dipakai.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_simpanActionPerformed

