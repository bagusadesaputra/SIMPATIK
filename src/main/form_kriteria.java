    private void t_cariKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_t_cariKeyTyped
        DefaultTableModel model = (DefaultTableModel) tabel_kriteria.getModel();
        model.setRowCount(0);
        
        String cari = t_cari.getText();
        
        try {
            String sql = "SELECT * FROM kriteria WHERE id LIKE ? OR nama_kriteria LIKE ? OR jenis_kriteria LIKE ? OR bobot LIKE ?";
            PreparedStatement st = conn.prepareStatement(sql);
                st.setString(1, "%" + cari + "%");
                st.setString(2, "%" + cari + "%");
                st.setString(3, "%" + cari + "%");
                st.setString(4, "%" + cari + "%");
            
            ResultSet rs = st.executeQuery();
            
            while(rs.next()) {
                String id      = rs.getString("id");
                String nama      = rs.getString("nama_kriteria");
                String jk      = rs.getString("jenis_kriteria");
                String bobot      = rs.getString("bobot");
                
                Object[] rowData = {id,nama,jk,bobot};
                model.addRow(rowData);
            }
            
            rs.close();
            st.close();
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error fetching kriteria data", e);
        }
    }//GEN-LAST:event_t_cariKeyTyped


