    private void btn_simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_simpanActionPerformed
        String kode = t_kode.getText();
        String nama = t_namaKriteria.getText();
        String jk = (String) combo_jenisKriteria.getSelectedItem();
        String bobot = t_bobot.getText();

        if(kode.isEmpty() || nama.isEmpty() || jk == null || jk.startsWith("--") || bobot.isEmpty()){
            JOptionPane.showMessageDialog(this, "Semua kolom harus diisi!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try {
            Double.parseDouble(bobot);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Bobot harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try {
            String sql = "INSERT INTO kriteria (id, nama_kriteria, jenis_kriteria, bobot) VALUES (?,?,?,?)";
            PreparedStatement st = conn.prepareStatement(sql);
            st.setString(1, kode);
            st.setString(2, nama);
            st.setString(3, jk);
            st.setString(4, bobot);

            int rowInserted = st.executeUpdate();
            if (rowInserted > 0){
                JOptionPane.showMessageDialog(this, "Data berhasil di input!");
                resetForm();
                getData();
            }
            st.close();
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error inserting kriteria data", e);
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data. Periksa apakah id kriteria sudah dipakai.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_simpanActionPerformed

