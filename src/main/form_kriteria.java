    private void getData() {
        DefaultTableModel model = (DefaultTableModel) tabel_kriteria.getModel();
        model.setRowCount(0);

        if (conn == null) {
            return; // Koneksi.getConnection() sudah menampilkan pesan error
        }

        String sql = "SELECT * FROM kriteria";

        try (PreparedStatement st = conn.prepareStatement(sql); ResultSet rs = st.executeQuery()) {

            while (rs.next()) {
                Object[] rowData = {
                    rs.getString("id"),
                    rs.getString("nama_kriteria"),
                    rs.getString("jenis_kriteria"),
                    rs.getString("bobot")
                };
                model.addRow(rowData);
            }

        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error fetching kriteria data", e);
        }
    }

