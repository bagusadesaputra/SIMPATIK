    private void btn_simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_simpanActionPerformed
        String kode = (String) combo_kodeKaryawan.getSelectedItem();
        if (kode == null || kode.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih kode karyawan!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Ambil & validasi c1-c10
        double[] nilai = new double[10];
        JTextField[] fields = {
            t_c1, t_c2, t_c3, t_c4, t_c5, t_c6, t_c7, t_c8, t_c9, t_c10
        };

        for (int i = 0; i < fields.length; i++) {
            String val = fields[i].getText().trim();
            if (val.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Semua kolom C1-C10 harus diisi!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            try {
                nilai[i] = Double.parseDouble(val);
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Nilai C" + (i + 1) + " harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        String sql = "INSERT INTO penilaian (kode_karyawan, c1, c2, c3, c4, c5, c6, c7, c8, c9, c10) "
        + "VALUES (?,?,?,?,?,?,?,?,?,?,?)";
        try (PreparedStatement st = conn.prepareStatement(sql)) {
            st.setString(1, kode);
            for (int i = 0; i < nilai.length; i++) {
                st.setDouble(i + 2, nilai[i]);
            }
            int rowInserted = st.executeUpdate();
            if (rowInserted > 0) {
                JOptionPane.showMessageDialog(this, "Data penilaian berhasil disimpan!");
                resetForm();
                getData();
            }
        } catch (SQLIntegrityConstraintViolationException e) {
            JOptionPane.showMessageDialog(this, "Kode karyawan tidak ditemukan di data karyawan!", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error inserting penilaian data", e);
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan saat menyimpan data.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_simpanActionPerformed

