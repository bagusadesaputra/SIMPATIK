    private void loadComboKaryawan() {
        combo_kodeKaryawan.removeAllItems();
        String sql = "SELECT kode_karyawan FROM karyawan";
        try (PreparedStatement st = conn.prepareStatement(sql); ResultSet rs = st.executeQuery()) {
            while (rs.next()) {
                combo_kodeKaryawan.addItem(rs.getString("kode_karyawan"));
            }
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error loading kode karyawan combo", e);
        }
    }

    private void setupComboListener() {
        combo_kodeKaryawan.addActionListener(evt -> {
            String kode = (String) combo_kodeKaryawan.getSelectedItem();
            if (kode == null) return;
            String sql = "SELECT nama FROM karyawan WHERE kode_karyawan = ?";
            try (PreparedStatement st = conn.prepareStatement(sql)) {
                st.setString(1, kode);
                try (ResultSet rs = st.executeQuery()) {
                    if (rs.next()) {
                        t_namaKaryawan.setText(rs.getString("nama"));
                    }
                }
            } catch (Exception e) {
                logger.log(Level.SEVERE, "Error fetching nama karyawan", e);
            }
        });
    }
        
    private void getData() {
        DefaultTableModel model = (DefaultTableModel) tabel_penilaian.getModel();
        model.setRowCount(0);
        if (conn == null) {
            return; // Koneksi.getConnection() sudah menampilkan pesan error
        }
        String sql = "SELECT p.id, p.kode_karyawan, k.nama, "
                   + "p.c1, p.c2, p.c3, p.c4, p.c5, p.c6, p.c7, p.c8, p.c9, p.c10 "
                   + "FROM penilaian p "
                   + "JOIN karyawan k ON p.kode_karyawan = k.kode_karyawan";
        try (PreparedStatement st = conn.prepareStatement(sql); ResultSet rs = st.executeQuery()) {
            while (rs.next()) {
                Object[] rowData = {
                    rs.getInt("id"),
                    rs.getString("kode_karyawan"),
                    rs.getString("nama"),
                    rs.getDouble("c1"),
                    rs.getDouble("c2"),
                    rs.getDouble("c3"),
                    rs.getDouble("c4"),
                    rs.getDouble("c5"),
                    rs.getDouble("c6"),
                    rs.getDouble("c7"),
                    rs.getDouble("c8"),
                    rs.getDouble("c9"),
                    rs.getDouble("c10")
                };
                model.addRow(rowData);
            }
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error fetching penilaian data", e);
        }
    }

