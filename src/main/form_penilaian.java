    private void btn_hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_hapusActionPerformed
        int selectedRow = tabel_penilaian.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data yang ingin dihapus!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) return;

        String sql = "DELETE FROM penilaian WHERE id=?";
        try (PreparedStatement st = conn.prepareStatement(sql)) {
            st.setInt(1, selectedId);
            int rowDeleted = st.executeUpdate();
            if (rowDeleted > 0) {
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
                resetForm();
                nonAktifButton();
                getData();
            }
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Error deleting penilaian data", e);
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan saat menghapus data.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_hapusActionPerformed

    private void btn_updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_updateActionPerformed
         int selectedRow = tabel_penilaian.getSelectedRow();
            if (selectedRow == -1) {
                JOptionPane.showMessageDialog(this, "Pilih data yang ingin di perbarui!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            JTextField[] fields = {
                t_c1, t_c2, t_c3, t_c4, t_c5, t_c6, t_c7, t_c8, t_c9, t_c10
            };
            double[] nilai = new double[10];

            for (int i = 0; i < fields.length; i++) {
                String val = fields[i].getText().trim();
                if (val.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Semua kolom C1-C10 harus diisi!", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                try {
                    nilai[i] = Double.parseDouble(val);
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Nilai C" + (i + 1) + " harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }

            String sql = "UPDATE penilaian SET c1=?, c2=?, c3=?, c4=?, c5=?, c6=?, c7=?, c8=?, c9=?, c10=? WHERE id=?";
            try (PreparedStatement st = conn.prepareStatement(sql)) {
                for (int i = 0; i < nilai.length; i++) {
                    st.setDouble(i + 1, nilai[i]);
                }
                st.setInt(11, selectedId);
                int rowUpdated = st.executeUpdate();
                if (rowUpdated > 0) {
                    JOptionPane.showMessageDialog(this, "Data penilaian berhasil diperbarui!");
                    resetForm();
                    nonAktifButton();
                    aktifButton();
                    getData();
                } else {
                    JOptionPane.showMessageDialog(this, "Data tidak ditemukan atau tidak ada perubahan.", "Info", JOptionPane.WARNING_MESSAGE);
                }
            } catch (Exception e) {
                logger.log(Level.SEVERE, "Error updating penilaian data", e);
                JOptionPane.showMessageDialog(this, "Terjadi kesalahan saat memperbarui data.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        mainPanel.removeAll();
        mainPanel.repaint();
        mainPanel.revalidate();

        mainPanel.add(dataPenilaian);
        mainPanel.repaint();
        mainPanel.revalidate();
    }//GEN-LAST:event_btn_updateActionPerformed

